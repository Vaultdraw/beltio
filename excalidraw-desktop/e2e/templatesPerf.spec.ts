import { writeFileSync } from "node:fs";

import { expect, type Page } from "@playwright/test";

import { test } from "./fixture";

import { openVault } from "./helpers";

// Performance measurements for the template picker (F9). Skipped unless
// E2E_PERF=1. Numbers go to stdout, and to markdown when PERF_MD is set
// (one file per browser: <PERF_MD without .md>-<browser>.md).
// Budget: first paint of the list < 100 ms p95 (200 templates); no long task
// > 50 ms caused by thumbnails.
const PERF = process.env.E2E_PERF === "1";
const RUNS = Number(process.env.PERF_RUNS ?? 10);
const COUNT = Number(process.env.PERF_TEMPLATES ?? 200);
const RATES = (process.env.PERF_RATES ?? "1,4").split(",").map(Number);
const OUT = process.env.PERF_MD;
const OPEN_BUDGET_MS = 100;
const LONG_TASK_BUDGET_MS = 50;

test.skip(!PERF, "set E2E_PERF=1 to run the template picker perf measurements");
test.describe.configure({ mode: "serial", timeout: 240_000 });
// Tracing snapshots the DOM inside the measured tasks; keep it out of the numbers.
test.use({ trace: "off" });

const pct = (values: number[], p: number) => {
  const sorted = [...values].sort((a, b) => a - b);
  return sorted[Math.min(sorted.length - 1, Math.ceil(p * sorted.length) - 1)];
};
const round = (n: number) => Math.round(n * 10) / 10;

const report: string[] = [];
const record = (title: string, rows: Record<string, unknown>) => {
  const line = `- ${title}: ${Object.entries(rows)
    .map(([k, v]) => `${k}=${typeof v === "number" ? round(v) : v}`)
    .join(", ")}`;
  report.push(line);
  // eslint-disable-next-line no-console
  console.log(`PERF ${line}`);
};

test.afterAll(({ browserName }) => {
  if (!OUT || report.length === 0) {
    return;
  }
  const body = [
    "# Template picker perf numbers (F9)",
    "",
    `Generated by e2e/templatesPerf.spec.ts (E2E_PERF=1), ${COUNT} templates of 5 shapes each, ${RUNS} runs per measurement.`,
    `Budgets: list first paint p95 < ${OPEN_BUDGET_MS} ms; no long task > ${LONG_TASK_BUDGET_MS} ms from thumbnails.`,
    "In-memory fake vault (no disk or IPC latency); real picker, real thumbnail renderer.",
    "",
    ...report,
    "",
  ].join("\n");
  writeFileSync(`${OUT.replace(/\.md$/, "")}-${browserName}.md`, body);
});

const installProbes = (page: Page) =>
  page.addInitScript(() => {
    const w = window as any;
    w.__lt = [];
    try {
      new PerformanceObserver((list) => {
        for (const e of list.getEntries()) {
          w.__lt.push({ start: e.startTime, dur: e.duration });
        }
      }).observe({ type: "longtask", buffered: true });
    } catch {
      /* webkit: no longtask API */
    }
    // One serialize per rendered thumbnail: counts renders vs cache hits.
    w.__renders = 0;
    const ser = XMLSerializer.prototype.serializeToString;
    XMLSerializer.prototype.serializeToString = function (...a: [Node]) {
      w.__renders++;
      return ser.apply(this, a);
    };
  });

/** Arms a one-shot probe: keydown -> first row in the DOM -> next paint. */
const armOpen = (page: Page) =>
  page.evaluate(() => {
    const w = window as any;
    const p: any = { t0: 0, tRow: 0, tPaint: 0 };
    w.__open = p;
    document.addEventListener(
      "keydown",
      () => {
        p.t0 = performance.now();
        const check = () => {
          if (!p.tRow && document.querySelector(".template-picker__row")) {
            p.tRow = performance.now();
            requestAnimationFrame(() =>
              requestAnimationFrame(() => (p.tPaint = performance.now())),
            );
            mo.disconnect();
          }
        };
        const mo = new MutationObserver(check);
        mo.observe(document.body, { childList: true, subtree: true });
      },
      { capture: true, once: true },
    );
  });

const readOpen = async (page: Page) => {
  await page.waitForFunction(() => (window as any).__open.tPaint > 0);
  return page.evaluate(() => {
    const p = (window as any).__open;
    return { rowMs: p.tRow - p.t0, paintMs: p.tPaint - p.t0, t0: p.t0 };
  });
};

const openPicker = async (page: Page) => {
  await armOpen(page);
  await page.keyboard.press("Control+Alt+N");
  return readOpen(page);
};

const closePicker = async (page: Page) => {
  await page.keyboard.press("Escape");
  await expect(page.locator(".template-picker")).toHaveCount(0);
};

test("picker open to first row, cold (fresh page each run)", async ({
  browser,
  browserName,
}, testInfo) => {
  const rowMs: number[] = [];
  const paintMs: number[] = [];
  for (let run = 0; run < RUNS; run++) {
    // A fresh context per run: nothing persisted (e.g. the last vault) leaks
    // between runs, so every run starts from the same cold state.
    const context = await browser.newContext(testInfo.project.use);
    const page = await context.newPage();
    await installProbes(page);
    await openVault(page, `?templates=${COUNT}`);
    const r = await openPicker(page);
    await expect(page.locator(".template-picker__row")).toHaveCount(COUNT + 1);
    rowMs.push(r.rowMs);
    paintMs.push(r.paintMs);
    await context.close();
  }
  record(`open ${browserName} cpu1x`, {
    templates: COUNT,
    runs: RUNS,
    firstRowP50Ms: pct(rowMs, 0.5),
    firstRowP95Ms: pct(rowMs, 0.95),
    firstPaintP50Ms: pct(paintMs, 0.5),
    firstPaintP95Ms: pct(paintMs, 0.95),
    paintMsRuns: JSON.stringify(paintMs.map(round)),
  });
  expect(pct(paintMs, 0.95)).toBeLessThan(OPEN_BUDGET_MS);
});

for (const rate of RATES) {
  test(`long tasks, thumbnails and cache hit, cpu${rate}x`, async ({
    page,
    browserName,
  }) => {
    test.skip(rate !== 1 && browserName !== "chromium", "CDP throttle");
    await installProbes(page);
    await openVault(page, `?templates=${COUNT}`);
    const cdp = rate === 1 ? null : await page.context().newCDPSession(page);
    await cdp?.send("Emulation.setCPUThrottlingRate", { rate });

    const tasksSince = (since: number) =>
      page.evaluate(
        (s) =>
          ((window as any).__lt as Array<{ start: number; dur: number }>)
            .filter((e) => e.start >= s)
            .map((e) => Math.round(e.dur)),
        since,
      );
    const tasksStartSince = (since: number) =>
      page.evaluate(
        (s) =>
          ((window as any).__lt as Array<{ start: number; dur: number }>)
            .filter((e) => e.start >= s)
            .map((e) => e.start),
        since,
      );
    const now = () => page.evaluate(() => performance.now());
    const renders = () => page.evaluate(() => (window as any).__renders);
    /** Waits until no thumbnail was rendered for `quietMs`. */
    const settle = async (quietMs = 800) => {
      let last = -1;
      let since = Date.now();
      for (;;) {
        const n = await renders();
        if (n !== last) {
          last = n;
          since = Date.now();
        } else if (Date.now() - since >= quietMs) {
          return n;
        }
        await page.waitForTimeout(100);
      }
    };

    // (a) cold open: long tasks from the keypress until thumbnails settle.
    const tStart = await now();
    const open = await openPicker(page);
    const visibleThumbs = () =>
      page.evaluate(() => {
        const scroll = document.querySelector(".template-picker__scroll")!;
        const box = scroll.getBoundingClientRect();
        const vis = [
          // Template rows only: the Blank row never has a thumbnail.
          ...document.querySelectorAll<HTMLElement>(
            ".template-picker__row[data-template-key]",
          ),
        ].filter((r) => {
          const b = r.getBoundingClientRect();
          return b.bottom > box.top && b.top < box.bottom;
        });
        return {
          visible: vis.length,
          withImg: vis.filter((r) => r.querySelector("img")).length,
        };
      });
    const coldRenders = await settle();
    const duringOpen = await tasksSince(tStart);
    const coldVisible = await visibleThumbs();

    // (b) scroll the whole list with thumbnails loading as rows appear.
    const tScroll = await now();
    const rendersBeforeScroll = await renders();
    const scrollHeight = await page.evaluate(() => {
      const el = document.querySelector(".template-picker__scroll")!;
      return el.scrollHeight - el.clientHeight;
    });
    const step = 160;
    for (let y = 0; y <= scrollHeight + step; y += step) {
      await page.evaluate(
        (top) =>
          (document.querySelector(".template-picker__scroll")!.scrollTop = top),
        y,
      );
      await page.waitForTimeout(40);
    }
    await settle(1200);
    const duringScroll = await tasksSince(tScroll);
    const scrollRenders = (await renders()) - rendersBeforeScroll;

    // (c) reopen: every thumbnail is cached (path + mtime + size).
    await closePicker(page);
    const rendersBeforeReopen = await renders();
    const tReopen = await now();
    const reopen = await openPicker(page);
    const t1 = Date.now();
    let reopenVisible = await visibleThumbs();
    while (
      reopenVisible.withImg < reopenVisible.visible &&
      Date.now() - t1 < 5000
    ) {
      await page.waitForTimeout(16);
      reopenVisible = await visibleThumbs();
    }
    const imagesAfterMs = Date.now() - t1;
    await page.waitForTimeout(500);
    const reopenRenders = (await renders()) - rendersBeforeReopen;
    const duringReopen = await tasksSince(tReopen);
    await cdp?.send("Emulation.setCPUThrottlingRate", { rate: 1 });

    const max = (l: number[]) => Math.max(0, ...l);
    record(`thumbnails ${browserName} cpu${rate}x`, {
      coldFirstRowMs: open.rowMs,
      coldFirstPaintMs: open.paintMs,
      coldRendersAfterOpen: coldRenders,
      coldVisibleRows: coldVisible.visible,
      coldVisibleWithThumb: coldVisible.withImg,
      scrollRenders,
      longTasksOpen:
        browserName === "chromium" ? duringOpen.length : "n/a (no longtask)",
      longTaskMaxOpenMs: browserName === "chromium" ? max(duringOpen) : "n/a",
      longTasksScroll:
        browserName === "chromium" ? duringScroll.length : "n/a (no longtask)",
      longTaskMaxScrollMs:
        browserName === "chromium" ? max(duringScroll) : "n/a",
      longTaskListOpen: JSON.stringify(duringOpen),
      longTaskOpenStartsAfterKeyMs: JSON.stringify(
        (await tasksStartSince(tStart)).map((t) => Math.round(t - open.t0)),
      ),
      longTaskListScroll: JSON.stringify(duringScroll),
      reopenFirstRowMs: reopen.rowMs,
      reopenFirstPaintMs: reopen.paintMs,
      reopenVisibleThumbsMs: imagesAfterMs,
      reopenRenders,
      reopenLongTasks: browserName === "chromium" ? duringReopen.length : "n/a",
    });

    expect(reopenRenders).toBe(0); // cache hit: nothing re-rendered
    if (browserName === "chromium") {
      expect(max(duringOpen)).toBeLessThanOrEqual(LONG_TASK_BUDGET_MS);
      expect(max(duringScroll)).toBeLessThanOrEqual(LONG_TASK_BUDGET_MS);
    }
  });
}
